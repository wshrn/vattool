fn ensure_icon() -> io::Result<()> {
    let icon_path = Path::new("icons/icon.ico");
    if !icon_path.exists() {
        if let Some(parent) = icon_path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(icon_path, ICON_BYTES)?;
        println!("cargo:warning=Generated default Windows icon at {}", icon_path.display());
    }
    Ok(())
}

fn main() {
    if let Err(error) = ensure_icon() {
        panic!("failed to ensure Windows icon: {}", error);
    }
    tauri_build::build()
}
